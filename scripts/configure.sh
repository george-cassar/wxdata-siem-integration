#!/usr/bin/env bash
# =============================================================================
# configure.sh — Interactive environment setup for the watsonx.data SIEM demo
# =============================================================================
# Asks every question needed to build a working .env, installs Python + Node
# dependencies, tests the Presto connection, and writes the file for you.
#
# Usage:
#   chmod +x scripts/configure.sh
#   ./scripts/configure.sh
#
# Re-run at any time to update your configuration.
# =============================================================================
set -euo pipefail

# ── Colour helpers ────────────────────────────────────────────────────────────
RESET='\033[0m'; BOLD='\033[1m'
GREEN='\033[0;32m'; YELLOW='\033[0;33m'; RED='\033[0;31m'
CYAN='\033[0;36m'; BLUE='\033[0;34m'; DIM='\033[2m'

banner()  { echo -e "\n${BOLD}${BLUE}── $* ${RESET}"; }
info()    { echo -e "  ${CYAN}·${RESET} $*"; }
ok()      { echo -e "  ${GREEN}✔${RESET}  $*"; }
warn()    { echo -e "  ${YELLOW}⚠${RESET}  $*"; }
err()     { echo -e "  ${RED}✘${RESET}  $*"; }
ask()     { echo -e "  ${BOLD}$*${RESET}"; }          # question label
hint()    { echo -e "  ${DIM}$*${RESET}"; }           # grey hint text

# ── Working directory: always repo root ──────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT_DIR"

ENV_FILE="$ROOT_DIR/.env"

# ── Read a line with a default value ─────────────────────────────────────────
# Usage: prompt_default VAR "Question" "default"
prompt_default() {
    local varname="$1" question="$2" default="$3"
    ask "$question"
    [ -n "$default" ] && hint "  (press Enter to accept: $default)"
    read -r -p "  → " input
    input="${input:-$default}"
    printf -v "$varname" '%s' "$input"
}

# ── Read a line — blank is allowed (no default hint shown) ───────────────────
prompt_optional() {
    local varname="$1" question="$2"
    ask "$question"
    hint "  (press Enter to leave blank)"
    read -r -p "  → " input
    printf -v "$varname" '%s' "$input"
}

# ── Read a masked password (no echo) ─────────────────────────────────────────
prompt_secret() {
    local varname="$1" question="$2"
    ask "$question"
    hint "  (input hidden)"
    read -r -s -p "  → " input
    echo ""   # newline after hidden input
    printf -v "$varname" '%s' "$input"
}

# ── Yes/No prompt, returns 0 for yes, 1 for no ───────────────────────────────
confirm() {
    local question="$1" default="${2:-y}"
    local prompt_str
    [ "$default" = "y" ] && prompt_str="[Y/n]" || prompt_str="[y/N]"
    ask "$question $prompt_str"
    read -r -p "  → " yn
    yn="${yn:-$default}"
    [[ "$yn" =~ ^[Yy] ]]
}

# ── Read current value of a key from .env (empty string if absent) ────────────
current_env() {
    local key="$1"
    if [ -f "$ENV_FILE" ]; then
        grep -E "^${key}=" "$ENV_FILE" | head -1 | cut -d= -f2- | sed "s/^['\"]//;s/['\"]$//"
    fi
}

