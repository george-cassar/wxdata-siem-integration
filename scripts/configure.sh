# ── Test Presto reachability using Python + trino ─────────────────────────────
test_presto_connection() {
    info "Testing Presto connection…"
    local py_script
    py_script=$(cat << 'PYEOF'
import sys, os

host   = os.environ.get("T_HOST", "")
port   = int(os.environ.get("T_PORT", "8443"))
user   = os.environ.get("T_USER", "ibmacp")
passwd = os.environ.get("T_PASS", "")
token  = os.environ.get("T_TOKEN", "")
use_ssl = os.environ.get("T_SSL", "false").lower() == "true"
verify  = os.environ.get("T_VERIFY", "true").lower() == "true"

def full_message(exc):
    """
    Walk the exception chain, deduplicating messages that repeat verbatim
    (common in urllib3/requests/trino chains) and returning only distinct lines.
    """
    parts = []
    seen_msgs = set()
    seen_ids  = set()
    e = exc
    while e is not None and id(e) not in seen_ids:
        seen_ids.add(id(e))
        msg = type(e).__name__ + ": " + str(e)
        # Use the str(e) part as the dedup key so repeated wrappers are collapsed
        key = str(e).strip()
        if key not in seen_msgs:
            seen_msgs.add(key)
            parts.append(msg)
        e = e.__cause__ or e.__context__
    return "\n".join(parts)

def get_cpd_token(cpd_host, user, passwd, verify):
    """
    Exchange CP4D username + password for a bearer token via
    POST /icp4d-api/v1/authorize.  Returns the token string.
    CP4D/watsonx.data Presto does NOT accept HTTP Basic Auth —
    it only accepts Authorization: Bearer <cpd-token>.
    """
    import urllib.request, urllib.error, json, ssl
    url = f"https://{cpd_host}/icp4d-api/v1/authorize"
    payload = json.dumps({"username": user, "password": passwd}).encode()
    req = urllib.request.Request(url, data=payload,
                                 headers={"Content-Type": "application/json"})
    ctx = ssl.create_default_context()
    if not verify:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
    with urllib.request.urlopen(req, context=ctx, timeout=10) as resp:
        body = json.loads(resp.read())
    t = body.get("token") or body.get("access_token")
    if not t:
        raise ValueError(f"No token in CP4D response: {list(body.keys())}")
    return t

try:
    import urllib.request, json, ssl, time

    # CP4D/watsonx.data Presto requires a bearer token, not HTTP Basic Auth.
    # If only a password was supplied, exchange it for a CP4D token first.
    if not token and passwd:
        cpd_host = os.environ.get("T_CPD_HOST", host)
        print(f"INFO:Fetching CP4D token from https://{cpd_host}/icp4d-api/v1/authorize …",
              file=sys.stderr)
        token = get_cpd_token(cpd_host, user, passwd, verify)
        print(f"INFO:Token obtained (first 12 chars): {token[:12]}…", file=sys.stderr)

    # Use the Presto HTTP REST protocol directly with X-Presto-User.
    # The trino Python client sends X-Trino-User which CP4D Presto (Java)
    # does not recognise, causing "400: User must be set".
    protocol = "https" if use_ssl else "http"
    url = f"{protocol}://{host}:{port}/v1/statement"
    headers = {
        "X-Presto-User": user,
        "X-Presto-Source": "watsonx-data-siem-demo",
        "Content-Type": "text/plain",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    ctx = ssl.create_default_context()
    if not verify:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE

    def presto_post(u, body=None, hdrs=None):
        req = urllib.request.Request(u, data=body, headers=hdrs or {})
        return urllib.request.urlopen(req, context=ctx, timeout=15)

    req_body = b"SHOW CATALOGS"
    with presto_post(url, req_body, headers) as r:
        data = json.loads(r.read())

    # Poll nextUri until terminal state
    all_rows = []
    columns = []
    while True:
        if data.get("columns") and not columns:
            columns = [c["name"] for c in data["columns"]]
        if data.get("data"):
            all_rows.extend(data["data"])
        state = data.get("stats", {}).get("state", "")
        next_uri = data.get("nextUri")
        if state in ("FINISHED", "FAILED", "CANCELED") or not next_uri:
            break
        time.sleep(0.2)
        with urllib.request.urlopen(
            urllib.request.Request(next_uri, headers={"Authorization": headers.get("Authorization", "")}),
            context=ctx, timeout=15
        ) as r:
            data = json.loads(r.read())

    catalogs = [row[0] for row in all_rows if row]
    print("OK:" + ",".join(catalogs))
except Exception as e:
    print("ERR:" + full_message(e))
PYEOF
)
    local result ok_line err_line

    # stderr (INFO progress lines, urllib3 warnings) goes to fd 3 → terminal.
    # stdout (the single OK:… or ERR:… line) is captured in $result.
    result=$(T_HOST="$PRESTO_HOST" T_PORT="$PRESTO_PORT" T_USER="$PRESTO_USER" \
             T_PASS="$PRESTO_PASSWORD" T_TOKEN="$PRESTO_BEARER_TOKEN" \
             T_CPD_HOST="${PRESTO_CPD_HOST:-$PRESTO_HOST}" \
             T_SSL="$PRESTO_USE_SSL" T_VERIFY="$PRESTO_SSL_VERIFY" \
             python3 -c "$py_script" 2>&3)

    # Extract the sentinel lines regardless of any extra output mixed in
    ok_line=$(echo "$result"  | grep '^OK:'  | tail -1)
    err_line=$(echo "$result" | grep '^ERR:' | tail -1)

    if [ -n "$ok_line" ]; then
        local catalogs="${ok_line#OK:}"
        ok "Connection successful!"
        info "Catalogs visible to user '${PRESTO_USER}': ${catalogs}"
        DETECTED_CATALOGS="$catalogs"
        return 0
    else
        err "Connection failed:"
        local errmsg="${err_line#ERR:}"
        # Fall back to full output when there is no ERR: line (e.g. Python crash)
        [ -z "$errmsg" ] && errmsg="$result"
        while IFS= read -r line; do
            echo -e "    ${RED}${line}${RESET}"
        done <<< "$errmsg"
        DETECTED_CATALOGS=""
        return 1
    fi
}

